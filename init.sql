CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS app_users (
    user_id SERIAL PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('ADMIN','CUSTOMER')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS branches (
    branch_id SERIAL PRIMARY KEY,
    branch_name VARCHAR(100) NOT NULL,
    city VARCHAR(80) NOT NULL,
    address VARCHAR(200) NOT NULL,
    phone VARCHAR(25) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS customers (
    customer_id SERIAL PRIMARY KEY,
    user_id INTEGER UNIQUE REFERENCES app_users(user_id) ON DELETE SET NULL,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    phone VARCHAR(25) NOT NULL UNIQUE,
    driver_license_no VARCHAR(40) NOT NULL UNIQUE,
    license_expiry DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS vehicles (
    vehicle_id SERIAL PRIMARY KEY,
    branch_id INTEGER NOT NULL REFERENCES branches(branch_id) ON DELETE RESTRICT,
    plate_no VARCHAR(15) NOT NULL UNIQUE,
    brand VARCHAR(50) NOT NULL,
    model VARCHAR(60) NOT NULL,
    model_year INTEGER NOT NULL CHECK (model_year BETWEEN 1990 AND 2035),
    category VARCHAR(30) NOT NULL,
    transmission VARCHAR(15) NOT NULL CHECK (transmission IN ('MANUAL','AUTOMATIC')),
    daily_rate NUMERIC(10,2) NOT NULL CHECK (daily_rate > 0),
    status VARCHAR(15) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (status IN ('AVAILABLE','RENTED','MAINTENANCE','INACTIVE'))
);

CREATE TABLE IF NOT EXISTS bookings (
    booking_id SERIAL PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(customer_id) ON DELETE RESTRICT,
    vehicle_id INTEGER NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE RESTRICT,
    pickup_branch_id INTEGER NOT NULL REFERENCES branches(branch_id) ON DELETE RESTRICT,
    return_branch_id INTEGER NOT NULL REFERENCES branches(branch_id) ON DELETE RESTRICT,
    pickup_date DATE NOT NULL,
    return_date DATE NOT NULL,
    booking_status VARCHAR(15) NOT NULL DEFAULT 'PENDING'
        CHECK (booking_status IN ('PENDING','CONFIRMED','COMPLETED','CANCELLED')),
    total_amount NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (return_date > pickup_date)
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id SERIAL PRIMARY KEY,
    booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(booking_id) ON DELETE CASCADE,
    payment_date DATE NOT NULL,
    amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('CARD','CASH','BANK_TRANSFER')),
    payment_status VARCHAR(15) NOT NULL CHECK (payment_status IN ('PAID','PENDING','REFUNDED'))
);

CREATE TABLE IF NOT EXISTS maintenance_records (
    maintenance_id SERIAL PRIMARY KEY,
    vehicle_id INTEGER NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE CASCADE,
    service_date DATE NOT NULL,
    description VARCHAR(250) NOT NULL,
    cost NUMERIC(10,2) NOT NULL CHECK (cost >= 0),
    next_service_date DATE
);

